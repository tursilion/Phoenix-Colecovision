#!/usr/bin/env python3
"""Make intv_roms_pack.vhd (EXEC, GROM, ECS and Intellivoice ROM contents)
and grom.hex (the GROM again, for the menu's text font) from the
Intellivision BIOS files.

  mkroms.py bios_dir out_dir

bios_dir has exec.bin (8192 bytes: 4096 big-endian words of 10-bit code),
grom.bin (2048 bytes), ecs.bin (24576 bytes: 12288 big-endian 10-bit
words) and sp0256-012.bin (2048 bytes, the Intellivoice's SP0256 ROM).
The outputs contain the BIOS, so they are made at build time and are not
kept in the repository.
"""
import sys, os


def words10(path, nbytes):
    d = open(path, 'rb').read()
    if len(d) != nbytes:
        sys.exit("mkroms: %s must be %d bytes" % (path, nbytes))
    w = [(d[2 * i] << 8) | d[2 * i + 1] for i in range(nbytes // 2)]
    if max(w) > 0x3FF:
        sys.exit("mkroms: %s has words wider than 10 bits" % path)
    return w


def raw(path, nbytes):
    d = open(path, 'rb').read()
    if len(d) != nbytes:
        sys.exit("mkroms: %s must be %d bytes" % (path, nbytes))
    return list(d)


def arr(vals, bits):
    lines = []
    for i in range(0, len(vals), 8):
        lines.append('    ' + ','.join('"%s"' % format(v, '0%db' % bits) for v in vals[i:i + 8]))
    return ',\n'.join(lines)


def main():
    bios, out = sys.argv[1:3]
    exe = words10(os.path.join(bios, 'exec.bin'), 8192)
    grom = raw(os.path.join(bios, 'grom.bin'), 2048)
    ecs = words10(os.path.join(bios, 'ecs.bin'), 24576)
    voice = raw(os.path.join(bios, 'sp0256-012.bin'), 2048)

    with open(os.path.join(out, 'intv_roms_pack.vhd'), 'w') as f:
        f.write('-- Generated by tools/mkroms.py from the Intellivision BIOS files.  Do not edit.\n')
        f.write('LIBRARY ieee;\nUSE ieee.std_logic_1164.ALL;\nUSE ieee.numeric_std.ALL;\n')
        f.write('LIBRARY work;\nUSE work.base_pack.ALL;\n\n')
        f.write('PACKAGE intv_roms_pack IS\n')
        f.write('  -- The EXEC and the ECS ROM are 10-bit code.\n')
        f.write('  TYPE arr_uv10 IS ARRAY(natural RANGE <>) OF uv10;\n')
        f.write('  CONSTANT EXEC_INIT : arr_uv10(0 TO 4095) := (\n%s);\n' % arr(exe, 10))
        f.write('  CONSTANT GROM_INIT : arr_uv8(0 TO 2047) := (\n%s);\n' % arr(grom, 8))
        for i in range(3):
            f.write('  CONSTANT ECS%d_INIT : arr_uv10(0 TO 4095) := (\n%s);\n' % (i, arr(ecs[4096 * i:4096 * (i + 1)], 10)))
        f.write('  CONSTANT VOICE_INIT : arr_uv8(0 TO 2047) := (\n%s);\n' % arr(voice, 8))
        f.write('END PACKAGE intv_roms_pack;\n')

    with open(os.path.join(out, 'grom.hex'), 'w') as f:
        for b in grom:
            f.write('%02x\n' % b)


main()
