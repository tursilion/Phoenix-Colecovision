#!/usr/bin/env python3
"""Make intv_roms_pack.vhd (EXEC and GROM ROM contents) and grom.hex (the
GROM again, for the menu's text font) from the Intellivision BIOS files.

  mkroms.py exec.bin grom.bin out_dir

exec.bin: 8192 bytes, 4096 big-endian 16-bit words (10-bit code).  grom.bin: 2048 bytes.
The outputs contain the BIOS, so they are made at build time and are not
kept in the repository.
"""
import sys, os

def main():
    exec_bin, grom_bin, out = sys.argv[1:4]
    e = open(exec_bin, 'rb').read()
    g = open(grom_bin, 'rb').read()
    if len(e) != 8192 or len(g) != 2048:
        sys.exit("mkroms: exec.bin must be 8192 bytes and grom.bin 2048 bytes")
    words = [(e[2 * i] << 8) | e[2 * i + 1] for i in range(4096)]

    if max(words) > 0x3FF:
        sys.exit("mkroms: exec.bin has words wider than 10 bits")

    def arr(vals, bits):
        lines = []
        for i in range(0, len(vals), 8):
            lines.append('    ' + ','.join('"%s"' % format(v, '0%db' % bits) for v in vals[i:i + 8]))
        return ',\n'.join(lines)

    with open(os.path.join(out, 'intv_roms_pack.vhd'), 'w') as f:
        f.write('-- Generated by tools/mkroms.py from exec.bin and grom.bin.  Do not edit.\n')
        f.write('LIBRARY ieee;\nUSE ieee.std_logic_1164.ALL;\nUSE ieee.numeric_std.ALL;\n')
        f.write('LIBRARY work;\nUSE work.base_pack.ALL;\n\n')
        f.write('PACKAGE intv_roms_pack IS\n')
        f.write('  -- The EXEC is 10-bit code.\n')
        f.write('  TYPE arr_uv10 IS ARRAY(natural RANGE <>) OF uv10;\n')
        f.write('  CONSTANT EXEC_INIT : arr_uv10(0 TO 4095) := (\n%s);\n' % arr(words, 10))
        f.write('  CONSTANT GROM_INIT : arr_uv8(0 TO 2047) := (\n%s);\n' % arr(list(g), 8))
        f.write('END PACKAGE intv_roms_pack;\n')

    with open(os.path.join(out, 'grom.hex'), 'w') as f:
        for b in g:
            f.write('%02x\n' % b)

main()
